"""
Room controller - API schema & handlers for room operations
"""
import logging
import secrets
import time
from datetime import datetime
from typing import Dict, Any, Optional

from src.modules.room.session_policy import (
    SessionPolicyFactory,
    normalize_room_config,
)
from src.shared.constants import ROOM_CODE_ALPHABET, ROOM_CODE_LENGTH, RoundStatus

logger = logging.getLogger(__name__)


def validate_create_room(data: Dict[str, Any]) -> tuple[bool, str]:
    """Validate create room request.

    ``room_id`` is generated by the server, so the only thing worth validating
    is the optional config payload.
    """
    config = (data or {}).get("config", data)
    if config is not None and not isinstance(config, dict):
        return False, "config must be an object"

    return True, ""


class RoomController:
    """Room controller - Handles room operations"""

    # The public directory is read on every page mount; a very short in-memory
    # cache avoids hammering Redis (one GET per room) for identical requests.
    PUBLIC_ROOMS_CACHE_TTL_SECONDS = 3.0

    def __init__(self, room_repository):
        self.room_repo = room_repository
        self._public_cache = None
        self._public_cache_at = 0.0

    def invalidate_public_cache(self) -> None:
        """Drop the cached directory after any room mutation."""
        self._public_cache = None
        self._public_cache_at = 0.0

    # ------------------------------------------------------------------ read

    async def list_rooms(self) -> list:
        """Get all rooms"""
        try:
            rooms = await self.room_repo.get_all_rooms()
            return rooms or []
        except Exception as e:
            logger.error(f"Error listing rooms: {e}")
            return []

    async def get_room(self, room_id: str) -> Optional[dict]:
        try:
            return await self.room_repo.find_info(room_id)
        except Exception as e:
            logger.error(f"Error reading room {room_id}: {e}")
            return None

    async def list_public_rooms(self, use_cache: bool = True) -> list:
        """Rooms anyone (including anonymous players) may browse and rejoin."""
        now = time.monotonic()
        if (
            use_cache
            and self._public_cache is not None
            and now - self._public_cache_at
            < self.PUBLIC_ROOMS_CACHE_TTL_SECONDS
        ):
            return self._public_cache

        rooms = await self.list_rooms()
        public = []
        for info in rooms:
            if info.get("status") in {"DELETED", "CLOSED"}:
                continue
            room_id = info.get("room_id")
            if not room_id:
                continue
            public.append(
                await self.public_room_view(
                    info, current_round=await self.get_current_round(room_id)
                )
            )
        public.sort(key=lambda room: room.get("created_at") or "", reverse=True)

        self._public_cache = public
        self._public_cache_at = time.monotonic()
        return public

    async def public_room_view(
        self, info: dict, current_round: Optional[int] = None
    ) -> dict:
        """Strip internal fields from a room record before showing it publicly."""
        config = SessionPolicyFactory.describe(info.get("config"))
        return {
            "room_id": info.get("room_id"),
            "owner_mc": info.get("owner_mc"),
            "mc_name": info.get("mc_name"),
            "player_count": info.get("player_count", 0),
            "status": info.get("status", "ACTIVE"),
            "current_round": current_round if current_round is not None else info.get("current_round", 0),
            "created_at": info.get("created_at"),
            "config": config,
        }

    async def list_rooms_for_mc(self, mc_username: str) -> list:
        """Rooms owned by a specific MC"""
        if not mc_username:
            return []
        try:
            rooms = await self.room_repo.get_all_rooms()
        except Exception as e:
            logger.error(f"Error listing rooms for MC '{mc_username}': {e}")
            return []
        return [
            room
            for room in (rooms or [])
            if room.get("owner_mc") == mc_username
            and room.get("status") not in {"DELETED", "CLOSED"}
        ]

    # ----------------------------------------------------------------- write

    async def save_room_info(self, room_id: str, info: dict) -> None:
        """Save room info"""
        try:
            await self.room_repo.save_info(room_id, info)
        except Exception as e:
            logger.error(f"Error saving room info: {e}")
            raise

    async def _generate_room_id(self) -> str:
        """Create a short, readable, unused room code."""
        for _ in range(25):
            room_id = "".join(
                secrets.choice(ROOM_CODE_ALPHABET) for _ in range(ROOM_CODE_LENGTH)
            )
            if not await self.room_repo.room_exists(room_id):
                return room_id
        # Extremely unlikely, but never hand out a duplicate.
        return "".join(
            secrets.choice(ROOM_CODE_ALPHABET) for _ in range(ROOM_CODE_LENGTH + 4)
        )

    async def create_room(
        self,
        config: Optional[dict] = None,
        owner_mc: Optional[str] = None,
        mc_name: Optional[str] = None,
    ) -> Dict[str, Any]:
        """Create a room with a server generated id and a normalised config."""
        try:
            room_id = await self._generate_room_id()
            normalized = normalize_room_config(config)
            room_info = {
                "room_id": room_id,
                "owner_mc": owner_mc,
                "mc_name": mc_name or owner_mc or "MC",
                "current_round": 0,
                "status": "ACTIVE",
                "created_at": datetime.now().isoformat(),
                "player_count": 0,
                "config": normalized,
            }
            await self.room_repo.save_info(room_id, room_info)
            self.invalidate_public_cache()
            logger.info(
                f"Room {room_id} created by MC '{owner_mc}' with config {normalized}"
            )
            return {
                "success": True,
                "message": "Room created successfully",
                "room": room_info,
                "config": SessionPolicyFactory.describe(normalized),
            }
        except Exception as e:
            logger.error(f"Error creating room: {e}")
            return {"success": False, "error": str(e)}

    async def update_room(
        self, room_id: str, config: dict, mc_username: Optional[str] = None
    ) -> Dict[str, Any]:
        """Patch a room's config. Only the owning MC may do this."""
        try:
            info = await self.room_repo.find_info(room_id)
            if not info:
                return {"success": False, "error": "Room not found"}

            owner = info.get("owner_mc")
            if owner and mc_username and owner != mc_username:
                return {"success": False, "error": "Room is owned by another MC"}

            merged = {**(info.get("config") or {}), **(config or {})}
            normalized = normalize_room_config(merged)
            info["config"] = normalized
            info["room_id"] = room_id
            await self.room_repo.save_info(room_id, info)
            self.invalidate_public_cache()
            logger.info(f"Room {room_id} config updated to {normalized}")
            return {
                "success": True,
                "room": info,
                "config": SessionPolicyFactory.describe(normalized),
            }
        except Exception as e:
            logger.error(f"Error updating room {room_id}: {e}")
            return {"success": False, "error": str(e)}

    async def delete_room(
        self, room_id: str, mc_username: Optional[str] = None
    ) -> Dict[str, Any]:
        """Delete a room and every cached key that belongs to it."""
        try:
            info = await self.room_repo.find_info(room_id)
            if not info:
                return {"success": False, "error": "Room not found"}

            owner = info.get("owner_mc")
            if owner and mc_username and owner != mc_username:
                return {"success": False, "error": "Room is owned by another MC"}

            deleted = await self.room_repo.delete_room(room_id)
            if not deleted:
                return {"success": False, "error": "Could not delete room"}
            self.invalidate_public_cache()
            return {"success": True, "room_id": room_id}
        except Exception as e:
            logger.error(f"Error deleting room {room_id}: {e}")
            return {"success": False, "error": str(e)}

    async def claim_room(
        self, room_id: str, mc_username: str, mc_name: str = None
    ) -> Dict[str, Any]:
        """
        Mark a room as owned by an MC.

        A room can only be claimed by one MC; a second MC cannot hijack it.
        """
        try:
            existing = await self.room_repo.find_info(room_id) or {}
            owner = existing.get("owner_mc")
            if owner and owner != mc_username:
                logger.warning(
                    f"MC '{mc_username}' attempted to claim room {room_id} "
                    f"already owned by '{owner}'"
                )
                return {"success": False, "error": "Room is owned by another MC"}

            existing.update(
                {
                    "room_id": room_id,
                    "owner_mc": mc_username,
                    "mc_name": mc_name or mc_username,
                }
            )
            existing.setdefault("created_at", datetime.now().isoformat())
            existing.setdefault("player_count", 0)
            existing.setdefault("current_round", 0)
            existing.setdefault("status", "ACTIVE")
            existing["config"] = normalize_room_config(existing.get("config"))
            await self.room_repo.save_info(room_id, existing)
            self.invalidate_public_cache()
            logger.info(f"Room {room_id} owned by MC '{mc_username}'")
            return {"success": True, "room": existing}
        except Exception as e:
            logger.error(f"Error claiming room {room_id}: {e}")
            return {"success": False, "error": str(e)}

    async def is_room_owner(self, room_id: str, mc_username: str) -> bool:
        """True when the given MC owns the room"""
        if not mc_username:
            return False
        try:
            info = await self.room_repo.find_info(room_id)
        except Exception as e:
            logger.error(f"Error checking owner of room {room_id}: {e}")
            return False
        if not info:
            return False
        return info.get("owner_mc") == mc_username

    # ---------------------------------------------------------------- rounds

    async def get_current_round(self, room_id: str) -> int:
        """Get authoritative current round of the room"""
        return await self.room_repo.get_current_round(room_id)

    async def start_round(self, room_id: str) -> int:
        """Advance room to the next round and mark it as accepting guesses"""
        round_id = await self.room_repo.next_round(room_id)
        await self.room_repo.set_round_status(room_id, RoundStatus.LOCKED)
        return round_id

    async def end_round(self, room_id: str) -> None:
        """Mark the current round as closed"""
        await self.room_repo.set_round_status(room_id, RoundStatus.ENDED)

    async def get_round_status(self, room_id: str) -> str:
        """Get current round status of the room"""
        return await self.room_repo.get_round_status(room_id)

    async def update_player_count(self, room_id: str) -> None:
        """Increment player count for room"""
        try:
            room_info = await self.room_repo.find_info(room_id)
            if room_info:
                room_info["player_count"] = room_info.get("player_count", 0) + 1
                await self.room_repo.save_info(room_id, room_info)
        except Exception as e:
            logger.error(f"Error updating player count: {e}")
